"""Small sqlite3-compatible facade backed by PostgreSQL.

The application historically used sqlite3 directly.  Keeping this narrow
facade lets the existing services share one PostgreSQL connection contract
while we migrate SQLite-only SQL in one place.
"""

from __future__ import annotations

import os
import re
from pathlib import Path
from types import SimpleNamespace
from typing import Any, Iterable

import psycopg2
from psycopg2 import extras
import sqlite3 as _stdlib_sqlite3
from dotenv import load_dotenv


PROJECT_ROOT = Path(__file__).resolve().parents[2]
load_dotenv(PROJECT_ROOT / ".env")


DATABASE_URL = os.getenv(
    "DATABASE_URL",
    "postgresql://postgres@127.0.0.1:5432/postgres",
)


def _adapt_sql(sql: str) -> str:
    sql = sql.strip()
    if sql.upper().startswith("PRAGMA "):
        return "SELECT 1"
    insert_ignore = "INSERT OR IGNORE INTO" in sql.upper()
    sql = sql.replace("INSERT OR IGNORE INTO", "INSERT INTO")
    if insert_ignore and "ON CONFLICT" not in sql.upper():
        sql += " ON CONFLICT DO NOTHING"
    sql = sql.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    sql = re.sub(r"\bFROM\s+sqlite_master\b", "FROM information_schema.tables", sql, flags=re.IGNORECASE)
    sql = sql.replace("type='table'", "table_type='BASE TABLE'").replace("type = 'table'", "table_type='BASE TABLE'")
    sql = sql.replace("name=?", "table_name=%s")
    return sql.replace("?", "%s")


class Cursor:
    def __init__(self, cursor: Any):
        self._cursor = cursor

    def fetchone(self):
        return self._cursor.fetchone()

    def fetchall(self):
        return self._cursor.fetchall()

    def __iter__(self):
        return iter(self._cursor)

    @property
    def lastrowid(self) -> int | None:
        try:
            with self._cursor.connection.cursor() as cursor:
                cursor.execute("SELECT lastval()")
                value = cursor.fetchone()
                return int(value[0]) if value else None
        except Exception:
            return None


class Connection:
    def __init__(self, _path: Path | str | None = None):
        self._connection = psycopg2.connect(DATABASE_URL, cursor_factory=extras.DictCursor)
        self.row_factory = None

    def execute(self, sql: str, params: Iterable[Any] | None = None) -> Cursor:
        cursor = self._connection.cursor()
        cursor.execute(_adapt_sql(sql), tuple(params) if params is not None else None)
        return Cursor(cursor)

    def cursor(self):
        """Expose a DB-API cursor for pandas and other integrations."""
        return self._connection.cursor()

    def executemany(self, sql: str, params: Iterable[Iterable[Any]]) -> Cursor:
        cursor = self._connection.cursor()
        cursor.executemany(_adapt_sql(sql), list(params))
        return Cursor(cursor)

    def executescript(self, script: str) -> None:
        for statement in (part.strip() for part in script.split(";")):
            if statement:
                self.execute(statement)

    def commit(self) -> None:
        self._connection.commit()

    def rollback(self) -> None:
        self._connection.rollback()

    def close(self) -> None:
        self._connection.close()

    def __enter__(self) -> "Connection":
        return self

    def __exit__(self, exc_type, exc_value, traceback) -> None:
        if exc_type:
            self.rollback()
        else:
            self.commit()
        self.close()


class Row(dict):
    """Compatibility marker for code that annotates sqlite3.Row."""


sqlite3 = SimpleNamespace(Connection=Connection, Row=Row, connect=None)


def connect(_path: Path | str | None = None) -> Connection:
    # Keep isolated unit-test databases working when an explicit temporary
    # *.db path is supplied. The application's aml.db token always resolves
    # to PostgreSQL.
    if isinstance(_path, Path) and _path.name != "aml.db" and _path.suffix == ".db":
        return _stdlib_sqlite3.connect(_path)
    return Connection(_path)


sqlite3.connect = connect
